from pathlib import Path

import yaml
from tqdm import tqdm


SOURCE_REVISION = "84fcc677e52e1902d696c32cd1a6b663e70d3993"
SOURCE_ROOT = (
    "https://raw.githubusercontent.com/anthropics/evals/"
    f"{SOURCE_REVISION}/advanced-ai-risk"
)
SPLIT_DIRECTORIES = {
    "fewshot": "prompts_for_few_shot_generation",
    "human": "human_generated_evals",
    "lm": "lm_generated_evals",
}


def source_url(dataset_name: str) -> str:
    split, subset = dataset_name.split("-", 1)
    if dataset_name == "human-self-awareness-web-gpt":
        subset = "self-awareness-web-gpt"
    return f"{SOURCE_ROOT}/{SPLIT_DIRECTORIES[split]}/{subset}.jsonl"


def main() -> None:
    task_root = Path(__file__).parent
    config_paths = sorted(task_root.glob("*.yaml"))
    for config_path in tqdm(config_paths):
        dataset_name = config_path.stem
        config_path.write_text(
            "# Generated by _generate_configs.py\n"
            + yaml.safe_dump(
                {
                    "include": "_template_yaml",
                    "task": f"advanced_ai_risk_{dataset_name}",
                    "dataset_kwargs": {
                        "data_files": {"validation": source_url(dataset_name)}
                    },
                },
                sort_keys=False,
            ),
            encoding="utf-8",
        )


if __name__ == "__main__":
    main()
